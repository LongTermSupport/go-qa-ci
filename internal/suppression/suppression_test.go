package suppression_test

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/LongTermSupport/go-qa-ci/internal/suppression"
)

// project writes files (slash-separated name to content) under a temporary root.
func project(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, text := range files {
		full := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func scan(t *testing.T, files map[string]string) suppression.Result {
	t.Helper()
	result, err := suppression.Scan(project(t, files), suppression.Options{})
	if err != nil {
		t.Fatal(err)
	}
	return result
}

// ruleLines flattens the suppressions to their String form for comparison.
func ruleLines(result suppression.Result) []string {
	out := make([]string, 0, len(result.Suppressions))
	for _, s := range result.Suppressions {
		out = append(out, s.String())
	}
	return out
}

func wantExactly(t *testing.T, got []string, want ...string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("got %q, want %q", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("entry %d: got %q, want %q", i, got[i], want[i])
		}
	}
}

// bodyLine is the line of a case body in the template used by TestGoDirectiveRoutes.
const bodyLine = "6"

func TestGoDirectiveRoutes(t *testing.T) {
	t.Parallel()
	here := "@p.go:" + bodyLine
	cases := []struct {
		name string
		body string
		want []string
	}{
		{"nolint with a reason", "x := f() " + nolint + ":errcheck // the error is reported elsewhere", []string{"errcheck" + here}},
		{"nolint naming several linters", "x := f() " + nolint + ":errcheck,gosec // both are accounted for elsewhere", []string{"errcheck" + here, "gosec" + here}},
		{"nolint with a space after the slashes", "x := f() " + spacedNo + ":errcheck // reason given", []string{"errcheck" + here}},
		{"bare nolint", "x := f() " + nolint, []string{"(none)" + here + " bare"}},
		{"nolint without a reason", "x := f() " + nolint + ":errcheck", []string{"errcheck" + here + " bare"}},
		{"nolint with an empty reason", "x := f() " + nolint + ":errcheck //", []string{"errcheck" + here + " bare"}},
		{"lint ignore", lintIgnore + " SA1019 the deprecated call is the point of this test\n\tx := f()", []string{"staticcheck::SA1019" + here}},
		{"lint file-ignore", fileIgnore + " ST1000 no package comment wanted here", []string{"staticcheck::ST1000" + here}},
		{"lint ignore of several checks", lintIgnore + " SA1019,SA1006 both are accepted in this block", []string{"staticcheck::SA1019" + here, "staticcheck::SA1006" + here}},
		{"lint ignore without a reason", lintIgnore + " SA1019", []string{"staticcheck::SA1019" + here + " bare"}},
		{"lint ignore of a non staticcheck name", lintIgnore + " custom-check we accept this class here", []string{"custom-check" + here}},
		{"gosec marker with a code", "x := f() " + gosecMark + " G104", []string{"gosec::G104" + here}},
		{"gosec marker with several codes and a reason", "x := f() " + gosecMark + " G104 G304 -- accounted for", []string{"gosec::G104" + here, "gosec::G304" + here}},
		{"bare gosec marker", "x := f() " + gosecMark, []string{"(none)" + here + " bare"}},
		{"ast-grep ignore with a rule", "x := f() " + astIgnore + ": no-panic", []string{"no-panic" + here}},
		{"ast-grep ignore of several rules", astIgnore + ": a-rule, b-rule", []string{"a-rule" + here, "b-rule" + here}},
		{"bare ast-grep ignore", astIgnore, []string{"(none)" + here + " bare"}},
		{"block comment directive", "/* " + spacedNo[3:] + ":errcheck // reason given */\n\tx := f()", []string{"errcheck" + here}},
		{"a comment that merely mentions the word", spacedNo + "lint checks the directives", nil},
		{"directive text inside a string", "s := \"" + nolint + ":errcheck\"\n\t_ = s", nil},
		{"directive text inside a raw string", "s := `\n" + nolint + "\n`\n\t_ = s", nil},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			source := "package p\n\nfunc f() error { return nil }\n\nfunc g() {\n\t" + tc.body + "\n}\n"
			wantExactly(t, ruleLines(scan(t, map[string]string{"p.go": source})), tc.want...)
		})
	}
}

func TestHandWrittenGeneratedHeaderIsASuppressionRoute(t *testing.T) {
	t.Parallel()
	result := scan(t, map[string]string{
		"gen.go":   "// Code generated by hand. DO NOT EDIT.\n\npackage p\n",
		"gen2.go":  "// Package p is autogenerated file output.\npackage p\n",
		"plain.go": "// Package p is documented.\npackage p\n",
		"after.go": "package p\n\n// Code generated mentions in the body are not headers.\nvar x = 1\n",
	})
	wantExactly(t, ruleLines(result), "go::generated-header@gen.go:1", "go::generated-header@gen2.go:1")
}

func TestUnparseableGoFileIsReported(t *testing.T) {
	t.Parallel()
	result := scan(t, map[string]string{"bad.go": "package p\nfunc (", "ok.go": "package p\n"})
	if len(result.Unparseable) != 1 || result.Unparseable[0].Path != "bad.go" || result.Unparseable[0].Message == "" {
		t.Fatalf("got %+v", result.Unparseable)
	}
	if len(result.Suppressions) != 0 {
		t.Errorf("got %q", ruleLines(result))
	}
}

func TestSkippedTreesExcludeGlobsAndScope(t *testing.T) {
	t.Parallel()
	directive := "package p\n\nfunc g() {\n\tf() " + nolint + ":errcheck // reason given\n}\n"
	root := project(t, map[string]string{
		"a/a.go":              directive,
		"b/b.go":              directive,
		"vendor/v/v.go":       directive,
		"testdata/t/t.go":     directive,
		"sub/testdata/t/t.go": directive,
		".git/hooks/h.go":     directive,
		"gen/skip.go":         directive,
	})
	all, err := suppression.Scan(root, suppression.Options{Exclude: []string{"gen/skip.go"}})
	if err != nil {
		t.Fatal(err)
	}
	wantExactly(t, ruleLines(all), "errcheck@a/a.go:4", "errcheck@b/b.go:4")
	scoped, err := suppression.Scan(root, suppression.Options{Scope: []string{"a"}, Exclude: []string{"gen"}})
	if err != nil {
		t.Fatal(err)
	}
	wantExactly(t, ruleLines(scoped), "errcheck@a/a.go:4")
}
