package suppression

import (
	"go/ast"
	"go/parser"
	"go/token"
	"regexp"
	"slices"
	"strings"
)

// The comment directives. Each is matched on one comment line with its comment markers removed.
var (
	// golangci-lint's disabling directive: the linter list (optional) and what follows it.
	disableDirective = regexp.MustCompile(`^nolint(?::(\S*))?(?:\s+(.*))?$`)
	// staticcheck's line and file ignores, with their checks and reason.
	ignoreDirective = regexp.MustCompile(`^lint:(?:file-)?ignore(?:\s+(\S+))?(?:\s+(\S.*))?$`)
	// gosec's marker may appear anywhere in a comment; what follows may hold G codes.
	gosecMarker = regexp.MustCompile(`#nosec(.*)$`)
	gosecCode   = regexp.MustCompile(`\bG\d+\b`)
	// ast-grep's ignore: the optional rule list follows a colon.
	astGrepMarker = regexp.MustCompile(`ast-grep-ignore(?::\s*(.*))?$`)
	// staticcheckCode matches the check codes staticcheck prints, which golangci-lint reports
	// under the linter name: the identifier go-qa prints is linter::code.
	staticcheckCode = regexp.MustCompile(`^(?:SA|S|ST|QF)\d{4}$`)
)

// generatedMarkers are the phrases golangci-lint's lax generated-file exclusion looks for, which
// include the standard header that go/ast recognises.
var generatedMarkers = []string{"code generated", "do not edit", "autogenerated file"}

// scanGo reads the comments of one Go file.
func scanGo(name string, data []byte) fileScan {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, name, data, parser.ParseComments)
	if err != nil {
		return unparseable(err)
	}
	var found []Suppression
	if line := generatedHeaderLine(fset, file); line > 0 {
		found = append(found, Suppression{Rule: "go::generated-header", Path: name, Line: line, Route: RouteGeneratedHeader})
	}
	for _, group := range file.Comments {
		for _, comment := range group.List {
			line := fset.Position(comment.Slash).Line
			for offset, text := range commentLines(comment.Text) {
				found = append(found, directives(name, line+offset, text)...)
			}
		}
	}
	return fileScan{found: found}
}

// generatedHeaderLine is the line of the comment before the package clause that marks the file as
// generated, or 0.
func generatedHeaderLine(fset *token.FileSet, file *ast.File) int {
	for _, group := range file.Comments {
		if group.Pos() >= file.Package {
			break
		}
		for _, comment := range group.List {
			lowered := strings.ToLower(comment.Text)
			for _, marker := range generatedMarkers {
				if strings.Contains(lowered, marker) {
					return fset.Position(comment.Slash).Line
				}
			}
		}
	}
	return 0
}

// commentLines returns the text of each line of a comment with the markers and surrounding space
// removed.
func commentLines(text string) []string {
	if rest, ok := strings.CutPrefix(text, "//"); ok {
		return []string{strings.TrimSpace(rest)}
	}
	text = strings.TrimSuffix(strings.TrimPrefix(text, "/*"), "*/")
	lines := strings.Split(text, "\n")
	for i, line := range lines {
		lines[i] = strings.TrimSpace(strings.TrimLeft(strings.TrimSpace(line), "*"))
	}
	return lines
}

// directives extracts the suppressions one comment line carries.
func directives(name string, line int, text string) []Suppression {
	var found []Suppression
	add := func(route Route, rules []string, bare string) {
		found = append(found, build(name, line, route, rules, bare)...)
	}
	if m := disableDirective.FindStringSubmatch(text); m != nil {
		linters := splitList(m[1])
		if slices.Contains(linters, "all") {
			// `all` silences every linter exactly as a bare directive does, so it is no named rule.
			add(RouteNolint, nil, "the directive names `all`, so it silences every linter on its line")
		} else {
			add(RouteNolint, linters, disableProblem(m))
		}
	}
	if m := ignoreDirective.FindStringSubmatch(text); m != nil {
		checks := splitList(m[1])
		for i, check := range checks {
			if staticcheckCode.MatchString(check) {
				checks[i] = "staticcheck::" + check
			}
		}
		add(RouteLintIgnore, checks, ignoreProblem(m))
	}
	if m := gosecMarker.FindStringSubmatch(text); m != nil {
		codes := gosecCode.FindAllString(beforeReason(m[1]), -1)
		for i, code := range codes {
			codes[i] = "gosec::" + code
		}
		bare := ""
		if len(codes) == 0 {
			bare = "the gosec marker names no rule, so it silences every gosec finding on its line"
		}
		add(RouteGosec, codes, bare)
	}
	if m := astGrepMarker.FindStringSubmatch(text); m != nil {
		rules := splitList(m[1])
		bare := ""
		if len(rules) == 0 {
			bare = "the ast-grep ignore names no rule, so it silences every rule on its line"
		}
		add(RouteAstGrep, rules, bare)
	}
	return found
}

// build makes one suppression per rule; a directive naming none yields a single bare one.
func build(name string, line int, route Route, rules []string, bare string) []Suppression {
	if len(rules) == 0 {
		if bare == "" {
			bare = "the directive names no rule"
		}
		return []Suppression{{Path: name, Line: line, Route: route, Bare: bare}}
	}
	out := make([]Suppression, 0, len(rules))
	for _, rule := range rules {
		out = append(out, Suppression{Rule: rule, Path: name, Line: line, Route: route, Bare: bare})
	}
	return out
}

func disableProblem(m []string) string {
	switch {
	case m[1] == "":
		return "the directive names no linter, so it silences every linter on its line"
	case !hasReason(m[2]):
		return "the directive gives no reason; write the linter list, then a double slash and the reason"
	default:
		return ""
	}
}

func ignoreProblem(m []string) string {
	switch {
	case m[1] == "":
		return "the directive names no check"
	case strings.TrimSpace(m[2]) == "":
		return "the directive gives no reason"
	default:
		return ""
	}
}

// hasReason reports whether the text after the linter list carries a double slash and a reason.
func hasReason(rest string) bool {
	reason, ok := strings.CutPrefix(strings.TrimSpace(rest), "//")
	return ok && strings.TrimSpace(reason) != ""
}

// beforeReason cuts a gosec justification (after two dashes) off the text after the marker.
func beforeReason(rest string) string {
	if i := strings.Index(rest, "--"); i >= 0 {
		return rest[:i]
	}
	return rest
}

// splitList splits a comma-separated list, dropping empty items.
func splitList(list string) []string {
	var items []string
	for item := range strings.SplitSeq(list, ",") {
		if item = strings.TrimSpace(item); item != "" {
			items = append(items, item)
		}
	}
	return items
}
